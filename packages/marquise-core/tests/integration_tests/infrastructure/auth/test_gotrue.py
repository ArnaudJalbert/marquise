"""Integration tests for the GoTrue authentication gateway."""

from __future__ import annotations

import json
import threading
import time
import urllib.parse
from collections.abc import Iterator
from contextlib import contextmanager
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

import pytest

from marquise.infrastructure.auth.gotrue import GoTrueAuthGateway
from marquise.interface_adapters.exceptions.auth import (
    AuthGatewayError,
    AuthGatewayUnavailableError,
)


class _QuietHandler(BaseHTTPRequestHandler):
    """Suppress local test-server request logs."""

    def log_message(self, format: str, *args: str) -> None:
        """Discard request logs generated by the local test server."""


class _ServiceUnavailableHandler(_QuietHandler):
    """Return an authentication-provider outage response."""

    def do_POST(self) -> None:
        """Return HTTP 503 for a token request."""
        self.send_error(503)


class _StalledHandler(_QuietHandler):
    """Accept a request without returning response data before timeout."""

    def do_POST(self) -> None:
        """Keep the connection open long enough for the client read to time out."""
        time.sleep(0.1)


class _PaginatedAccountsHandler(_QuietHandler):
    """Return the exact account only on the second filtered page."""

    requested_pages: list[str] = []

    def do_GET(self) -> None:
        """Return one full partial-match page followed by the exact account."""
        query = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query)
        page = query["page"][0]
        self.requested_pages.append(page)
        if page == "1":
            users = [{"email": f"target+{index}@example.com"} for index in range(50)]
        else:
            users = [{"id": "expected", "email": "TARGET@example.com"}]
        body = json.dumps({"users": users}).encode()
        self.send_response(200)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)


@contextmanager
def _serve(handler: type[BaseHTTPRequestHandler]) -> Iterator[str]:
    """Run a local HTTP server for one gateway integration scenario."""
    server = ThreadingHTTPServer(("127.0.0.1", 0), handler)
    thread = threading.Thread(target=server.serve_forever)
    thread.start()
    host, port = server.server_address
    try:
        yield f"http://{host}:{port}"
    finally:
        server.shutdown()
        server.server_close()
        thread.join()


@pytest.mark.asyncio
async def test_http_503_is_reported_as_service_unavailable() -> None:
    """Provider HTTP 5xx responses preserve the availability failure contract."""
    with _serve(_ServiceUnavailableHandler) as auth_url:
        gateway = GoTrueAuthGateway(
            auth_url, publishable_key="key", allow_insecure_local_http=True
        )

        with pytest.raises(AuthGatewayUnavailableError):
            await gateway.issue_access_token("admin@example.com", "secret")


@pytest.mark.asyncio
async def test_read_timeout_is_reported_as_service_unavailable() -> None:
    """A stalled provider response becomes a stable availability failure."""
    with _serve(_StalledHandler) as auth_url:
        gateway = GoTrueAuthGateway(
            auth_url,
            publishable_key="key",
            timeout_seconds=0.01,
            allow_insecure_local_http=True,
        )

        with pytest.raises(AuthGatewayUnavailableError):
            await gateway.issue_access_token("admin@example.com", "secret")


@pytest.mark.asyncio
async def test_find_by_email_searches_until_exact_match() -> None:
    """Filtered account lookup checks later pages for an exact email match."""
    _PaginatedAccountsHandler.requested_pages = []
    with _serve(_PaginatedAccountsHandler) as auth_url:
        gateway = GoTrueAuthGateway(
            auth_url, service_role_key="service-key", allow_insecure_local_http=True
        )

        account = await gateway.find_by_email("target@example.com")

    assert account == {"id": "expected", "email": "TARGET@example.com"}
    assert _PaginatedAccountsHandler.requested_pages == ["1", "2"]


@pytest.mark.asyncio
@pytest.mark.parametrize("status", [301, 302, 303, 307, 308])
@pytest.mark.parametrize("password_request", [False, True])
@pytest.mark.parametrize("same_origin", [False, True])
async def test_redirect_never_receives_credentials(
    status: int, password_request: bool, same_origin: bool
) -> None:
    """Redirects never forward service keys or password requests to a target."""
    received: list[str] = []

    class Destination(_QuietHandler):
        def do_GET(self) -> None:
            received.append(self.path)
            self.send_response(200)
            self.end_headers()

    with _serve(Destination) as destination:

        class Redirect(_QuietHandler):
            def do_GET(self) -> None:
                if self.path == "/capture":
                    received.append(self.path)
                    self.send_response(200)
                    self.end_headers()
                    return
                self.send_response(status)
                self.send_header(
                    "Location", "/capture" if same_origin else f"{destination}/capture"
                )
                self.end_headers()

            def do_POST(self) -> None:
                self.do_GET()

        with _serve(Redirect) as origin:
            gateway = GoTrueAuthGateway(
                origin,
                service_role_key="dummy-service-key",
                publishable_key="dummy-publishable-key",
                allow_insecure_local_http=True,
            )
            with pytest.raises(AuthGatewayError, match="redirects"):
                if password_request:
                    await gateway.issue_access_token(
                        "user@example.com", "dummy-password"
                    )
                else:
                    await gateway.find_by_email("user@example.com")

    assert received == []
